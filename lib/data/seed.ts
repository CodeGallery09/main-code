/**
 * 90 days of daily activity, generated from a fixed formula so the numbers never move between
 * renders (a real store would read these from an events table).
 */
export function buildTrend(days = 90, endISO = "2026-10-12T00:00:00.000Z"): TrendPoint[] {
  const end = new Date(endISO).getTime();
  const out: TrendPoint[] = [];
  for (let i = days - 1; i >= 0; i -= 1) {
    const date = new Date(end - i * 86_400_000);
    const dow = date.getUTCDay();
    const weekend = dow === 0 || dow === 6;
    const wave = Math.sin(i / 6.5) * 0.28 + Math.cos(i / 17) * 0.16;
    const base = weekend ? 26 : 112 + i * 0.35;
    const reached = Math.max(8, Math.round(base * (1 + wave)));
    const engaged = Math.round(reached * (weekend ? 0.44 : 0.62));
    const replied = Math.round(reached * (weekend ? 0.05 : 0.071));
    const positive = Math.round(replied * 0.5);
    const meetings = Math.round(positive * 0.34);
    out.push({
      date: date.toISOString().slice(0, 10),
      reached,
      engaged,
      replied,
      positive,
      meetings,
    });
  }
  return out;
}

